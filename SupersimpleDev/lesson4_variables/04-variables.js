// Store a simple numeric value in a variable.
let firstNumber = 2;
console.log(firstNumber); // Output: 2

// Perform a calculation and save the result.
let sum = 2 + 2;
console.log(sum); // Output: 4

// Use the stored value in another calculation.
console.log(sum + 2); // Output: 6

// The value of 'sum' does not change unless it is reassigned.
console.log(sum + 2); // Output: 6

console.log("//==============================================");

// Store the new calculation in a separate variable.
let finalResult = sum + 2;
console.log(finalResult); // Output: 6

let stringname = 'hello'
console.log(stringname);
console.log(stringname + 'World');

console.log("//==============================================");

